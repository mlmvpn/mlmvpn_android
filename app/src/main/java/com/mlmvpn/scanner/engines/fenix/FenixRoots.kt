    private val ALL = listOf(GLOBALSIGN_R46, GLOBALSIGN_E46)

    /** Xray's `tlsSettings.certificates`: each root as a `verify` entry, added to the system pool. */
    fun xrayCertificates(): List<List<String>> = ALL.map { it.lines() }

    /** A socket factory trusting the phone's roots plus these two; the default one if that fails. */
    val socketFactory: SSLSocketFactory by lazy {
        runCatching {
            val merged = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
            val system = KeyStore.getInstance("AndroidCAStore").apply { load(null, null) }
            for (alias in system.aliases()) {
                (system.getCertificate(alias) as? X509Certificate)?.let { merged.setCertificateEntry("system:$alias", it) }
            }
            val factory = CertificateFactory.getInstance("X.509")
            ALL.forEachIndexed { i, pem ->
                merged.setCertificateEntry("fenix:$i", factory.generateCertificate(ByteArrayInputStream(pem.toByteArray(Charsets.US_ASCII))))
            }
            val tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(merged) }
            SSLContext.getInstance("TLS").apply { init(null, tmf.trustManagers, null) }.socketFactory
        }.getOrElse { SSLSocketFactory.getDefault() as SSLSocketFactory }
    }
