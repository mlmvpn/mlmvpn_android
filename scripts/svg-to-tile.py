"""Turns the owner's logo SVG into a home-tile vector drawable.

The tile artwork convention (see ui/home/AppIcon.kt TileFace): a 1024 viewport whose own squircle
ground is inset to 90% (51.2 .. 972.8), drawn as is, never clipped by the tile. The owner's SVGs are
full-bleed squares, so the whole drawing is scaled onto the squircle's box and clipped to it.

Usage: python -I svg2vd.py <in.svg> <out.xml> <title>
"""
import sys
import xml.etree.ElementTree as ET

SQUIRCLE = (
    "M651.264 51.2c92.16 0 138.24 0 188.416 15.36 54.272 19.456 97.28 62.464 116.736 116.736"
    "C972.8 233.472 972.8 280.576 972.8 372.736v278.528c0 92.16 0 138.24-15.36 188.416-19.456 "
    "54.272-62.464 97.28-116.736 116.736-51.2 16.384-97.28 16.384-189.44 16.384H372.736c-92.16 0-"
    "138.24 0-188.416-15.36-55.296-20.48-97.28-62.464-117.76-117.76C51.2 790.528 51.2 744.448 51.2 "
    "651.264V372.736c0-92.16 0-138.24 15.36-188.416 20.48-54.272 62.464-97.28 117.76-116.736"
    "C233.472 51.2 279.552 51.2 372.736 51.2h278.528z"
)
BOX_FROM, BOX_SIZE = 51.2, 921.6

def main() -> None:
    src, out, title = sys.argv[1], sys.argv[2], sys.argv[3]
    root = ET.parse(src).getroot()
    ns = "{http://www.w3.org/2000/svg}"
    vb = [float(v) for v in root.get("viewBox").split()]
    if vb[0] != 0 or vb[1] != 0 or vb[2] != vb[3]:
        raise SystemExit("expected a square viewBox from the origin, got %r" % vb)
    scale = BOX_SIZE / vb[2]
    paths = root.findall(".//" + ns + "path")
    if not paths:
        raise SystemExit("no paths")
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!--",
        "    Home tile «%s»: the owner's logo file (%s), drawn on the tiles' own squircle." % (title, src.replace("\\", "/").split("/")[-1]),
        "    Generated by scripts/svg-to-tile.py; the paths are the SVG's own, unchanged. The right to",
        "    use this logo in a release is not yet established (docs/URNETWORK-NPV-PLAN.md, 15.7).",
        "-->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="1024"',
        '    android:viewportHeight="1024">',
        "    <group>",
        '        <clip-path android:pathData="%s" />' % SQUIRCLE,
        '        <group android:translateX="%s" android:translateY="%s" android:scaleX="%.6f" android:scaleY="%.6f">'
        % (BOX_FROM, BOX_FROM, scale, scale),
    ]
    for p in paths:
        d = p.get("d")
        fill = p.get("fill")
        if not d or not fill or not fill.startswith("#"):
            raise SystemExit("a path without data or a plain colour fill")
        attrs = [
            'android:fillColor="%s"' % fill,
            'android:pathData="%s"' % d,
        ]
        if p.get("fill-rule") == "evenodd":
            attrs.append('android:fillType="evenOdd"')
        stroke = p.get("stroke")
        if stroke and stroke.startswith("#"):
            attrs.append('android:strokeColor="%s"' % stroke)
            attrs.append('android:strokeWidth="%s"' % (p.get("stroke-width") or "1"))
            if p.get("stroke-linejoin") == "round":
                attrs.append('android:strokeLineJoin="round"')
        lines.append("            <path")
        for a in attrs:
            lines.append("                " + a)
        lines[-1] += " />"
    lines += ["        </group>", "    </group>", "</vector>", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("%s: %d paths, scale %.6f" % (out, len(paths), scale))

if __name__ == "__main__":
    main()
