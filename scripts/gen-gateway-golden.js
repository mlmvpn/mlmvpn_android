// Golden fixtures for the central Worker's links: what the WINDOWS app's manager builds, byte for
// byte, from fixed inputs. The Android side (engines/gateway/GatewayLinks + GatewayEngine) must give
// exactly the same links — that is what «the same Worker on the phone and on the desktop» means for
// the configs both devices hand out.
//
// Run from the monorepo root (it needs ../../edge-gateway, which the standalone Android repo lacks):
//     node android/scripts/gen-gateway-golden.js
// It rewrites app/src/test/resources/gateway_golden.json. Commit the result.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const { createManager, DEFAULT_SETTINGS, readModules } = require(path.join(ROOT, 'edge-gateway', 'manager.js'));
const links = require(path.join(ROOT, 'edge-gateway', 'links.js'));

const RECORD = {
    accId: 'golden', panel: 'BPB', script: 'app-core-a3f2b1-gw', host: 'app-core-a3f2b1-gw.mysub.workers.dev',
    url: 'https://app-core-a3f2b1-gw.mysub.workers.dev', uuid: '0b5c4f1e-6d2a-4c9b-8f31-7a2d9e4c1b60', wsPath: '/a1b2c3d4e5f60718',
    fallback: 'bpb.yousef.isegaro.com', codeHash: 'x', at: 1790700000000,
    panels: { EDG: { uuid: '11111111-2222-4333-8444-555555555555', at: 1790700000000 }, NTR: { uuid: '66666666-7777-4888-8999-aaaaaaaaaaaa', at: 1790700000000 } },
};
const DNS = { A: ['104.21.8.12', '172.67.140.9'], AAAA: ['2606:4700:3030::6815:80c', '2606:4700:3036::ac43:8c09'] };

const CASES = [
    { name: 'BPB with the defaults', panel: 'BPB', settings: {} },
    { name: 'Edge with IPv6, two ports, clean IPs and a domain', panel: 'EDG', settings: { cleanIPs: ['104.16.1.1', 'zula.ir', '2606:4700::1111'], ports: [443, 8443], ipv6: true } },
    { name: 'Netra with no resolved addresses and no method links', panel: 'NTR', settings: { withResolved: false, methods: false } },
    { name: 'BPB on 8443 only (no :443 link to build the methods from)', panel: 'BPB', settings: { ports: [8443], cleanIPs: ['www.speedtest.net'] } },
];

async function build(c) {
    const records = { golden: JSON.parse(JSON.stringify(Object.assign({}, RECORD, { settings: Object.assign({}, DEFAULT_SETTINGS, c.settings, { cleanIPs: c.settings.cleanIPs || DEFAULT_SETTINGS.cleanIPs, ports: c.settings.ports || DEFAULT_SETTINGS.ports }) }))) };
    const store = { get: (k) => (records[k] ? JSON.parse(JSON.stringify(records[k])) : null), put: (k, v) => { records[k] = JSON.parse(JSON.stringify(v)); return records[k]; }, del: (k) => { delete records[k]; } };
    const gtFetch = async (url) => {
        const type = new URL(url).searchParams.get('type');
        return { ok: true, status: 200, text: async () => JSON.stringify({ Answer: DNS[type].map((d) => ({ type: type === 'AAAA' ? 28 : 1, data: d })) }) };
    };
    const registry = { get: async () => null, put: async () => true, remove: async () => true, scriptExists: async () => true };
    const cf = { API: 'x', account: (id) => ({ id }), accountId: async () => 'A', headers: () => ({}), workerName: (s) => 'x' + s, enableWorkersDev: async () => {}, removeWorker: async () => {} };
    const m = createManager({ cf, axios: {}, store, gtFetch, registry });
    const r = await m.configs('golden', { panel: c.panel });
    return r.configs;
}

(async () => {
    const out = {
        note: 'Generated by android/scripts/gen-gateway-golden.js from the Windows app (edge-gateway/manager.js). Do not edit by hand.',
        record: RECORD,
        dns: DNS,
        defaults: DEFAULT_SETTINGS,
        vless: [
            { uuid: RECORD.uuid, host: RECORD.host, wsPath: RECORD.wsPath, name: 'BPB-x-Domain', port: 443, address: null },
            { uuid: RECORD.uuid, host: RECORD.host, wsPath: RECORD.wsPath, name: 'Édge — ایران 1', port: 8443, address: '104.16.1.1' },
            { uuid: RECORD.uuid, host: RECORD.host, wsPath: RECORD.wsPath, name: 'v6', port: 2053, address: '2606:4700::1111' },
        ].map((c) => ({ in: c, expected: links.vlessLink({ uuid: c.uuid, host: c.host, wsPath: c.wsPath, name: c.name, port: c.port, address: c.address || undefined }) })),
        cases: [],
        modulesHash: readModules().hash,
    };
    for (const c of CASES) out.cases.push({ name: c.name, panel: c.panel, settings: c.settings, expected: await build(c) });
    const dest = path.join(__dirname, '..', 'app', 'src', 'test', 'resources', 'gateway_golden.json');
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, JSON.stringify(out, null, 1) + '\n');
    console.log('wrote', dest, out.cases.map((c) => c.expected.length).join(','), 'links; modules hash', out.modulesHash);
})().catch((e) => { console.error(e); process.exit(1); });
